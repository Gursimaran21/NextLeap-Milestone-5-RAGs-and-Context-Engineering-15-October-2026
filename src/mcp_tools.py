"""MCP-style tool layer used by the Streamlit app.

Two "destructive" tools are exposed — exactly the two required by the brief:
  1. append_to_notes(entry)            -> appends to a Notes/Doc (mock Notion/Google Doc)
  2. create_email_draft(subject, body) -> creates an email DRAFT (never sends)

Both are GATED: they require an approval token issued by ApprovalGate.approve().
If the token was not approved, they raise PermissionError and write nothing.
"""

from __future__ import annotations

import hashlib
import json
from datetime import datetime, date, timezone
from email.message import EmailMessage
from pathlib import Path

from . import config


# --------------------------------------------------------------------------- entry
def build_note_entry(insights: dict, pulse_md: str, explainer: dict) -> dict:
    """The exact payload the brief requires MCP to log."""
    return {
        "date": date.today().isoformat(),
        "top_themes": insights["top_themes"],
        "weekly_pulse": pulse_md.strip(),
        "identified_fee_issue": insights["fee_issue"]["label"],
        "explanation_bullets": explainer["bullets"],
        "source_links": [s["url"] for s in explainer["sources"]],
    }


def email_subject() -> str:
    return f"Weekly Product Pulse + Customer Clarification — Groww (Week of {date.today().isoformat()})"


def build_email_body(insights: dict, pulse_md: str, explainer: dict) -> str:
    bullets = "\n".join(f"- {b}" for b in explainer["bullets"])
    links = "\n".join(f"- {s['name']}: {s['url']}" for s in explainer["sources"])
    return f"""{pulse_md.strip()}

---

## Reusable support snippet — {insights['fee_issue']['label']}

{bullets}

Sources:
{links}

Last checked: {explainer['last_checked']}

---
Generated by the Groww Review Insights Analyser. No PII. Draft only — not sent.
"""


# --------------------------------------------------------------------------- approval
class ApprovalGate:
    """Issues/validates approval tokens and logs every decision."""

    def __init__(self, log_path: Path = config.APPROVAL_LOG) -> None:
        self.log_path = log_path
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        self._approved: set[str] = set()
        self._rejected: set[str] = set()

    @staticmethod
    def token_for(action: str, payload: dict) -> str:
        blob = action + json.dumps(payload, sort_keys=True, default=str)
        return hashlib.sha256(blob.encode("utf-8")).hexdigest()[:16]

    def request(self, action: str, payload: dict) -> str:
        token = self.token_for(action, payload)
        self._log("REQUESTED", action, token)
        return token

    def approve(self, action: str, payload: dict, approver: str = "streamlit_user") -> str:
        token = self.token_for(action, payload)
        self._approved.add(token)
        self._rejected.discard(token)
        self._log("APPROVED", action, token, approver=approver)
        return token

    def reject(self, action: str, payload: dict, approver: str = "streamlit_user") -> str:
        token = self.token_for(action, payload)
        self._rejected.add(token)
        self._log("REJECTED", action, token, approver=approver)
        return token

    def require(self, action: str, payload: dict) -> None:
        token = self.token_for(action, payload)
        if token not in self._approved:
            self._log("BLOCKED", action, token)
            raise PermissionError(
                f"approval_required: '{action}' was called without an approved token."
            )

    def _log(self, decision: str, action: str, token: str, approver: str = "", ) -> None:
        rec = {
            "ts": datetime.now(timezone.utc).isoformat(),
            "decision": decision,
            "action": action,
            "token": token,
            "approver": approver,
        }
        with self.log_path.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(rec) + "\n")


# --------------------------------------------------------------------------- tools
def append_to_notes(entry: dict, gate: ApprovalGate) -> dict:
    """MCP tool 1 — append the structured entry to the Notes/Doc."""
    gate.require("append_to_notes", entry)

    config.ensure_dirs()
    # JSON log (machine-readable, the "Notion DB row")
    rows: list[dict] = []
    if config.NOTES_JSON.exists():
        try:
            rows = json.loads(config.NOTES_JSON.read_text(encoding="utf-8"))
        except Exception:
            rows = []
    rows.append(entry)
    config.NOTES_JSON.write_text(json.dumps(rows, indent=2), encoding="utf-8")

    # Human-readable Doc (the "Google Doc / Notion page" snippet)
    block = [
        f"\n## {entry['date']} — Weekly Pulse Entry\n",
        f"**Top themes:** {', '.join(entry['top_themes'])}",
        f"**Identified fee issue:** {entry['identified_fee_issue']}\n",
        "**Weekly pulse**\n",
        entry["weekly_pulse"],
        "\n**Explanation bullets**\n",
        "\n".join(f"- {b}" for b in entry["explanation_bullets"]),
        "\n**Source links**\n",
        "\n".join(f"- {u}" for u in entry["source_links"]),
        "\n---\n",
    ]
    header = "# Groww — Notes / Weekly Log\n"
    existing = config.NOTES_MD.read_text(encoding="utf-8") if config.NOTES_MD.exists() else header
    if not existing.strip().startswith("#"):
        existing = header + existing
    config.NOTES_MD.write_text(existing.rstrip() + "\n" + "\n".join(block), encoding="utf-8")

    return {
        "tool": "append_to_notes",
        "status": "appended",
        "rows_in_doc": len(rows),
        "doc_file": str(config.NOTES_MD),
        "json_file": str(config.NOTES_JSON),
    }


def create_email_draft(subject: str, body: str, gate: ApprovalGate, sender: str = "me@example.com") -> dict:
    """MCP tool 2 — create an email DRAFT. Never sends."""
    payload = {"subject": subject, "body": body}
    gate.require("create_email_draft", payload)

    config.ensure_dirs()
    msg = EmailMessage()
    msg["From"] = sender
    msg["To"] = sender  # send to self / alias
    msg["Subject"] = subject
    msg.set_content(body)

    config.EMAIL_EML.write_text(msg.as_string(), encoding="utf-8")
    config.EMAIL_MD.write_text(f"Subject: {subject}\n\n{body}", encoding="utf-8")

    draft_id = hashlib.sha1(subject.encode("utf-8")).hexdigest()[:12]
    return {
        "tool": "create_email_draft",
        "status": "draft_created",
        "draft_id": f"draft_{draft_id}",
        "to": sender,
        "eml_file": str(config.EMAIL_EML),
        "md_file": str(config.EMAIL_MD),
    }


def read_pending_batch() -> dict:
    """MCP helper — read generated artifacts so the agent can submit them."""
    out: dict = {}
    for key, path in (("pulse", config.PULSE_JSON), ("explainer", config.EXPLAINER_JSON),
                      ("insights", config.INSIGHTS_JSON)):
        if path.exists():
            out[key] = json.loads(path.read_text(encoding="utf-8"))
    return out


